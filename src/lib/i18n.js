export function translate(lang, key, vars) {
  const table = DICT[lang] || DICT.en
  let s = table[key]
  if (s === undefined) s = DICT.en[key]
  if (s === undefined) return key
  if (vars) for (const k of Object.keys(vars)) s = s.replaceAll('{' + k + '}', String(vars[k]))
  return s
}
